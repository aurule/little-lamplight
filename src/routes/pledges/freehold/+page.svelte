<h1>The Freehold Pledge</h1>

<p><i>This pledge is typically sworn by all the Lost who live in Little Lamplight. It is re-sworn every season under that season's monarch.</i></p>

<p>By the light that burns in shadow, I bind my heart to this Freehold.</p>
<p>I shall guard its borders as I guard my dreams, speak truth to my kin, and raise my hand in defense when darkness comes.</p>
<p>Let my Glamour sour and my luck wither should I betray this trust, until the moon forgets my name.</p>

<hr />

<p><b>Boons:</b> +2 to all social rolls when trying to preserve the peace within the borders of Little Lamplight</p>

<p><b>Sanctions:</b> Betrayal inflicts the <i>Coward's Brand</i> – a visible, thorn-shaped scar that imposes -3 to all Persuasion rolls with changelings until magically removed.</p>

<p><b>Duration:</b> 1 season.</p>
