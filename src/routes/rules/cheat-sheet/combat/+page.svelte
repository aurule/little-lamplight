<h1>Combat Cheat Sheet</h1>

<p>A quick reference for fighting, compiled by Wade.</p>

<h2>The Basics</h2>

<p><b>Attack roll =</b> Attribute + Skill + Equipment + Power + Merit - Opponent's Defense</p>

<p>You deal one point of damage for each success on your attack roll. The damage type is determined by your weapon, but is usually Bashing for fists and Lethal for everything else.</p>

<h2>Modifiers</h2>

